const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const written: string[] = []

function emit(rel: string, body: string): void {
  const file = path.join(root, rel)
  mkdirSync(path.dirname(file), { recursive: true })
  writeFileSync(file, body.trimStart())
  written.push(rel)
}

const NOTE = (what: string) =>
  `<!-- ${what}. Generated by scripts/gen-brand.ts from apps/web/app/lib/mark.ts — do not edit. -->`

/**
 * Rewrite a marked region inside a hand-written file.
 *
 * The prose around the mark stays human; the numbers in it do not. Every
 * measured claim — hexes, contrast ratios, the size each ratio lands at — used
 * to be typed into `DESIGN.md`, `brand/README.md` and the ADR separately, and
 * the one that mattered ("validated down to 16px… floor 4.30:1… zero
 * failures") was still sitting there being false while the favicon was
 * illegible. ADR-0052 made "keep in sync" a check for the geometry; this is
 * the same check for the prose (ADR-0054).
 */
function replaceRegion(rel: string, key: string, body: string): void {
  const file = path.join(root, rel)
  // MDX has no HTML comments — `<!--` is a parse error there, not a comment,
  // so the markers take the JSX-expression form in `.mdx` and the HTML form in
  // plain markdown. Worth knowing rather than guessing: both docs pages failed
  // to compile the first time this ran, and only loading the route said so.
  const mdx = rel.endsWith(".mdx")
  const wrap = (text: string) => (mdx ? `{/* ${text} */}` : `<!-- ${text} -->`)
  const open = wrap(`gen:${key}`)
  const close = wrap(`/gen:${key}`)
  const current = readFileSync(file, "utf8")
  const from = current.indexOf(open)
  const to = current.indexOf(close)
  if (from === -1 || to === -1) {
    throw new Error(`${rel}: missing ${open} … ${close} markers`)
  }
  const next =
    current.slice(0, from + open.length) +
    `\n${wrap("Generated by scripts/gen-brand.ts — do not edit by hand.")}\n\n${body.trim()}\n\n` +
    current.slice(to)
  if (next !== current) writeFileSync(file, next)
  written.push(`${rel} (${key})`)
}

function luminance(hex: string): number {
  const v = Number.parseInt(hex.slice(1), 16)
  const channel = (c: number) => {
    const s = c / 255
    return s <= 0.04045 ? s / 12.92 : ((s + 0.055) / 1.055) ** 2.4
  }
  return (
    0.2126 * channel((v >> 16) & 0xff) +
    0.7152 * channel((v >> 8) & 0xff) +
    0.0722 * channel(v & 0xff)
  )
}

function contrast(a: string, b: string): string {
  const [hi, lo] = [luminance(a), luminance(b)].sort((x, y) => y - x)
  return ((hi + 0.05) / (lo + 0.05)).toFixed(2)
}

/**
 * Worst case for a tone across the surfaces it is actually asked to hold.
 *
 * `mode` scopes it: the bare glyph is keyed on mode, so the light ember only
 * ever lands on a light theme's surfaces and measuring it against a dark
 * theme's page answers a question nobody asked. The chip takes no mode, and
 * faces all of them.
 */
function worstGround(
  hex: string,
  mode?: "light" | "dark",
): { ratio: string; where: string } {
  let worst = { ratio: Number.POSITIVE_INFINITY, where: "" }
  for (const [name, theme] of themeEntries) {
    if (mode && theme.mode !== mode) continue
    for (const [tier, surface] of [
      ["page", theme.tokens.bg],
      ["card", theme.tokens.bg1],
    ] as const) {
      const r = Number(contrast(hex, surface))
      if (r < worst.ratio) worst = { ratio: r, where: `${name} ${tier}` }
    }
  }
  return { ratio: worst.ratio.toFixed(2), where: worst.where }
}

/**
 * A markdown table, already padded the way the formatter would pad it.
 *
 * Not cosmetic. `oxfmt` aligns table columns to their widest cell; a generator
 * that emits them unpadded and a formatter that pads them rewrite each other
 * forever, and CI — which runs both and then fails on a dirty tree — would
 * never go green. Emitting the canonical form is what makes the generated
 * region a fixed point.
 */
function table(header: string[], rows: string[][]): string {
  const all = [header, ...rows]
  const width = header.map((_, i) =>
    Math.max(...all.map((r) => (r[i] ?? "").length)),
  )
  const line = (cells: string[]) =>
    `| ${cells.map((c, i) => (c ?? "").padEnd(width[i])).join(" | ")} |`
  return [
    line(header),
    `| ${width.map((w) => "-".repeat(Math.max(w, 3))).join(" | ")} |`,
    ...rows.map(line),
  ].join("\n")
}

