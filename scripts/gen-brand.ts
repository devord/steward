/**
 * Generate every static identity asset from the one geometry (ADR-0052/0053).
 *
 * Run `node scripts/gen-brand.ts`; CI re-runs it and fails if the working
 * tree moves, so none of the output is ever hand-edited. That check is the
 * whole point of the script. The bow tie used to exist as six independent
 * copies of the same path data, each carrying a comment asking the next
 * editor to keep them in sync by hand. They are now all renders of
 * `apps/web/app/lib/mark.ts`.
 *
 * Writes:
 *   brand/                    the distributable kit (see brand/README.md)
 *   apps/web/public/favicon.svg, wordmark-{light,dark}.svg
 *   templates/data-repo/.github/wordmark-{light,dark}.svg
 *   scripts/icon.svg, scripts/icon-maskable.svg   (raster sources)
 *
 * Rasters are NOT written here: `scripts/render-icons.sh` drives them through
 * headless Chrome, because ImageMagick's SVG delegate is not faithful to the
 * gradients.
 *
 * ## Two framings, and one of them stopped switching
 *
 * The **bare glyph** is mode-keyed: it sits on a surface it does not own, so
 * it takes the light or dark ember. The **chip** is a single colourway in both
 * modes (ADR-0053) — it is a saturated object rather than a surface, and
 * making it follow the viewer's mode produced a polarity flip that read as two
 * different logos. That is why `favicon.svg` no longer carries a
 * `prefers-color-scheme` block, and why there is one `steward-icon.svg`
 * instead of a light, a dark and an auto.
 */
